// Run against the real bundled Vue editor, in an isolated browser/profile.
module.exports = async function verifyRenderer() {
  const results = [];
  const errors = [];
  const onError = event => errors.push(event.message || String(event.reason));
  window.addEventListener('error', onError);
  window.addEventListener('unhandledrejection', onError);
  const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
  const check = (ok, name) => { if (!ok) throw new Error(name); results.push(name); };
  async function wait(predicate) {
    for (let i = 0; i < 150; i++) { if (predicate()) return; await sleep(20); }
    throw new Error('等待页面状态超时');
  }
  const components = () => {
    const all = [];
    function visit(v) { all.push(v); (v.$children || []).forEach(visit); }
    visit(document.querySelector('#app').__vue__);
    return all;
  };
  const app = document.querySelector('#app').__vue__;
  const node = (text, uid, children = []) => ({ data: { text, uid, checked: false }, children });
  const fixture = { root: node('<p><span style="font-weight: bold; color: rgb(255, 0, 0);">旧中心</span></p>', 'root', [
    node('父任务', 'parent', [node('任务甲', 'a'), node('任务乙', 'b')]), node('普通任务', 'plain'),
  ]), theme: { template: 'classic4', config: {} }, layout: 'logicalStructure', view: null };
  fixture.root.data.richText = true;
  localStorage.setItem('MIND_MAP_FILE_LIST', JSON.stringify([{ id: 'verify', name: '旧标题', createdAt: '2026-10-08', updatedAt: '2026-10-08' }]));
  localStorage.setItem('MIND_MAP_FILE_DATA_verify', JSON.stringify(fixture));
  // Exercise first use without relying on a previously dismissed download tip.
  localStorage.removeItem('webUseTip');
  const stored = () => JSON.parse(localStorage.getItem('MIND_MAP_FILE_DATA_verify'));
  const title = () => JSON.parse(localStorage.getItem('MIND_MAP_FILE_LIST'))[0].name;
  await app.$router.push('/').catch(() => {});
  await wait(() => components().some(v => v.$options.name === 'HomePage'));
  let home = components().find(v => v.$options.name === 'HomePage');
  home.loadFiles();
  await home.$nextTick();
  check(home.fileList[0].name === '旧标题' && window.MindListModel.visibleText(stored().root.data.text) === '旧中心', '旧清单不同名称保持不变');
  const row = uid => components().find(v => v.$options.name === 'NodeItem' && v.node.data.uid === uid);
  row('a').$el.querySelector('.cbWrap').click();
  await home.$nextTick();
  check(window.MindListModel.isPartial(stored().root.children[0]) && row('parent').isIndeterminate, '清单视图显示部分完成');
  row('b').toggleCheck();
  check(stored().root.children[0].data.checked && stored().root.data.checked === false, '清单子任务全部完成时父任务完成');
  home.onDesktopEdit('undo');
  check(!stored().root.children[0].data.checked && !stored().root.children[0].children[1].data.checked, '清单一次撤销同时恢复父子状态');
  home.onDesktopEdit('redo');
  check(stored().root.children[0].data.checked, '清单重做恢复父子状态');
  const card = components().find(v => v.$options.name === 'ChecklistCard');
  card.onAddChild(row('parent').node);
  check(!stored().root.children[0].data.checked && window.MindListModel.isPartial(stored().root.children[0]), '清单新增待办让已完成父任务变成部分完成');
  home.onDesktopEdit('undo');
  check(stored().root.children[0].data.checked && stored().root.children[0].children.length === 2, '撤销新增同时恢复层级和完成状态');
  home.renameChecklist('verify', '标题改名');
  check(title() === '标题改名' && window.MindListModel.visibleText(stored().root.data.text) === '标题改名', '顶部标题同步中心主节点');
  check(stored().root.data.text.includes('font-weight: bold') && stored().root.data.text.includes('color:'), '标题改名保留主节点格式');
  await home.$nextTick();
  const homeWrite = Storage.prototype.setItem;
  Storage.prototype.setItem = function (key, value) {
    if (key === 'MIND_MAP_FILE_DATA_verify') throw new Error('验证清单保存失败');
    return homeWrite.call(this, key, value);
  };
  row('plain').toggleCheck();
  await app.$router.push('/edit?id=verify').catch(() => {});
  check(app.$route.path === '/' && home.fileDataCache.verify.root.children[1].data.checked && !stored().root.children[1].data.checked, '清单保存失败时保留当前修改并阻止切换丢失');
  Storage.prototype.setItem = homeWrite;
  check(home.flushCardSaves() && stored().root.children[1].data.checked, '清单恢复保存后可继续操作');
  home.onDesktopEdit('undo');
  check(!stored().root.children[1].data.checked, '清单保存恢复后可撤销');
  await home.$nextTick();
  Storage.prototype.setItem = function (key, value) {
    if (key === 'MIND_MAP_FILE_DATA_verify') throw new Error('验证撤销前保存失败');
    return homeWrite.call(this, key, value);
  };
  row('plain').toggleCheck();
  home.onDesktopEdit('undo');
  check(!stored().root.children[1].data.checked && home.pendingCardSaves.verify.root.children[1].data.checked, '保存仍失败时撤销保留待保存修改');
  Storage.prototype.setItem = homeWrite;
  home.onDesktopEdit('undo');
  check(!stored().root.children[1].data.checked && !home.pendingCardSaves.verify && !home.fileDataCache.verify.root.children[1].data.checked, '保存恢复后直接撤销最后待保存操作');
  home.loadFiles();
  home.flushCardSaves();
  check(!stored().root.children[1].data.checked, '重新加载不会恢复已撤销的待保存状态');
  home.onDesktopEdit('redo');
  check(stored().root.children[1].data.checked && !home.pendingCardSaves.verify, '待保存操作撤销后重做与存储一致');
  home.onDesktopEdit('undo');
  await home.$nextTick();
  Storage.prototype.setItem = function (key, value) {
    if (key === 'MIND_MAP_FILE_DATA_verify') throw new Error('验证改名前保存失败');
    return homeWrite.call(this, key, value);
  };
  row('plain').toggleCheck();
  Storage.prototype.setItem = homeWrite;
  home.renameChecklist('verify', '恢复后改名');
  check(!home.pendingCardSaves.verify && stored().root.children[1].data.checked && title() === '恢复后改名', '待保存修改恢复后直接改名保留任务状态');
  home.loadFiles();
  home.flushCardSaves();
  check(window.MindListModel.visibleText(stored().root.data.text) === '恢复后改名' && title() === '恢复后改名', '改名后加载和保存不会恢复旧名称');
  await home.$nextTick();
  row('plain').toggleCheck();
  await app.$router.push('/edit?id=verify');
  await wait(() => components().some(v => v.mindMap && v._checkboxInstanceMap && v.mindMap.renderer.root));
  let editor = components().find(v => v.mindMap && v._checkboxInstanceMap);
  let map = editor.mindMap;
  const runtime = uid => {
    let found;
    function visit(n) { if (n.getData('uid') === uid) found = n; (n.children || []).forEach(visit); }
    visit(map.renderer.root);
    return found;
  };
  const clickCheck = uid => editor._checkboxInstanceMap.get(runtime(uid)).$el.click();
  const visible = (uid, checked) => {
    const n = runtime(uid), text = n._textData.node.node;
    check(!!text.textContent.trim() && text.isConnected && text.getAttribute('opacity') !== '0', uid + ' 文字完整可见');
    const strike = text.outerHTML.includes('line-through');
    check(strike === checked, uid + ' 删除线与勾选状态一致');
  };
  await sleep(450);
  check(!document.querySelector('.el-message-box__wrapper') && !document.body.innerText.includes('网页版已暂停更新') && localStorage.getItem('webUseTip') === null, '首次打开不显示停止更新弹窗');
  const parent = runtime('parent');
  await map.renderer.textEdit.show({ node: parent });
  const before = !!parent.getData('checked');
  clickCheck('parent');
  await sleep(450);
  check(!map.renderer.textEdit.isShowTextEdit(), '编辑中勾选会提交文字并收起编辑框');
  visible('parent', !before);
  check(stored().root.children[0].data.checked === !before, '勾选自动保存');
  map.execCommand('BACK');
  await sleep(450);
  check(map.getData().children[0].data.checked === before && stored().root.children[0].data.checked === before, '导图撤销与保存内容一致');
  map.execCommand('FORWARD');
  await sleep(450);
  check(map.getData().children[0].data.checked === !before, '导图重做恢复勾选');
  const historyBefore = map.command.history.length;
  for (let i = 0; i < 40; i++) clickCheck('parent');
  await sleep(450);
  check(map.command.history.length === historyBefore + 40, '40 次快速勾选分别进入撤销记录');
  visible('parent', !before);
  visible('a', !before);
  map.execCommand('SET_NODE_EXPAND', runtime('parent'), false);
  await sleep(180);
  clickCheck('parent');
  map.execCommand('SET_NODE_EXPAND', runtime('parent'), true);
  await sleep(450);
  check(map.getData().children[0].children.every(n => n.data.checked === before), '折叠时勾选仍同步全部子节点');
  visible('a', before);
  if (!runtime('parent').getData('checked')) clickCheck('parent');
  await sleep(200);
  map.execCommand('INSERT_CHILD_NODE', false, [runtime('parent')], { text: '新增待办', checked: false });
  await sleep(450);
  check(!runtime('parent').getData('checked') && window.MindListModel.isPartial(map.getData().children[0]), '导图新增待办更新父任务状态');
  map.execCommand('BACK');
  await sleep(450);
  check(runtime('parent').getData('checked') && runtime('parent').children.length === 2, '导图撤销新增恢复父子状态');
  map.execCommand('FORWARD');
  await sleep(450);
  check(!runtime('parent').getData('checked') && runtime('parent').children.length === 3, '导图重做新增恢复部分完成');
  map.execCommand('REMOVE_NODE', [runtime('parent').children[2]]);
  await sleep(450);
  check(runtime('parent').getData('checked') && runtime('parent').children.length === 2, '删除最后未完成子任务后父任务完成');
  map.execCommand('BACK');
  await sleep(450);
  check(!runtime('parent').getData('checked') && runtime('parent').children.length === 3, '撤销删除恢复待办及部分完成');
  map.execCommand('FORWARD');
  await sleep(450);
  map.execCommand('MOVE_NODE_TO', [runtime('a')], runtime('plain'));
  await sleep(450);
  check(runtime('plain').getData('checked') && runtime('plain').children.length === 1 && runtime('parent').children.length === 1, '移动子节点后新旧父任务状态正确');
  map.execCommand('BACK');
  await sleep(450);
  check(!runtime('plain').getData('checked') && runtime('parent').children.length === 2, '撤销移动恢复层级和原完成状态');
  map.execCommand('MOVE_NODE_TO', [runtime('a')], runtime('plain'));
  map.execCommand('BACK');
  await sleep(450);
  check(runtime('parent').children.length === 2 && runtime('plain').children.length === 0, '移动后立即撤销也能恢复层级');
  map.setMode('readonly');
  const readonlyChecked = runtime('parent').getData('checked');
  clickCheck('parent');
  check(runtime('parent').getData('checked') === readonlyChecked, '只读状态不能意外勾选');
  map.setMode('edit');
  map.execCommand('SET_NODE_TEXT', map.renderer.root, '<p><span style="font-weight: bold;">中心改名</span></p>', true);
  await sleep(450);
  check(title() === '中心改名', '中心主节点反向同步清单标题');
  for (const layout of ['mindMap', 'catalogOrganization', 'logicalStructure']) {
    map.setLayout(layout);
    await sleep(400);
    check(stored().layout === layout && map.getData().children[0].children.length === 2, layout + ' 布局及层级保存');
  }
  const exportData = await map.export('smm', false);
  check(!!exportData, '原有清单导出可用');
  const exported = JSON.parse(await (await fetch(exportData)).text());
  map.setFullData(exported);
  await sleep(450);
  check(map.getData().children[0].children.length === 2 && window.MindListModel.visibleText(map.getData().data.text) === '中心改名', '导出内容重新导入保留名称和子层级');
  const originalWrite = Storage.prototype.setItem;
  const oldText = stored().root.children[1].data.text;
  Storage.prototype.setItem = function (key, value) {
    if (key === 'MIND_MAP_FILE_DATA_verify') throw new Error('验证保存失败');
    return originalWrite.call(this, key, value);
  };
  map.execCommand('SET_NODE_TEXT', runtime('plain'), '<p>失败后待保存</p>', true);
  await sleep(450);
  check(stored().root.children[1].data.text === oldText && !!document.querySelector('#mindlist-save-error[role="alert"]'), '保存失败保留旧数据并显示提醒');
  await app.$router.push('/').catch(() => {});
  check(app.$route.path === '/edit' && components().includes(editor), '保存失败时保留当前编辑页和未保存修改');
  const closing = new Event('beforeunload', { cancelable: true });
  window.dispatchEvent(closing);
  check(closing.defaultPrevented, '保存失败时阻止直接关闭丢失修改');
  Storage.prototype.setItem = originalWrite;
  editor.manualSave();
  check(window.MindListModel.visibleText(stored().root.children[1].data.text) === '失败后待保存' && !document.getElementById('mindlist-save-error'), '恢复保存后保留新修改并清除失败提醒');
  // Route away immediately after a command, before either debounce finishes.
  map.execCommand('SET_NODE_TEXT', runtime('plain'), '<p>退出前修改</p>', true);
  await app.$router.push('/');
  await sleep(450);
  check(window.MindListModel.visibleText(stored().root.children[1].data.text) === '退出前修改', '退出页面前的最后修改写入正确清单');
  const homeClosing = new Event('beforeunload', { cancelable: true });
  window.dispatchEvent(homeClosing);
  check(!homeClosing.defaultPrevented, '退出编辑页后释放关闭窗口的检查');
  await app.$router.push('/edit?id=verify');
  await wait(() => components().some(v => v.mindMap && v._checkboxInstanceMap && v.mindMap.renderer.root));
  editor = components().find(v => v.mindMap && v._checkboxInstanceMap);
  map = editor.mindMap;
  await sleep(400);
  check(window.MindListModel.visibleText(map.getData().children[1].data.text) === '退出前修改' && title() === '中心改名', '重新打开保留名称、层级和最后修改');
  check(!document.querySelector('.el-message-box__wrapper') && localStorage.getItem('webUseTip') === null, '再次打开不显示停止更新弹窗');
  window.removeEventListener('error', onError);
  window.removeEventListener('unhandledrejection', onError);
  check(errors.length === 0, '整条状态流转没有未处理的页面错误');
  return { checks: results, rapidChecks: 40, checklistId: 'verify' };
};
